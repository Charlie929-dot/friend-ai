# 各类语料上一次抽中的下标：防连续重复（人味儿 = 不重样）
_last_idx: dict[str, int] = {}


def pick(items: list[str], key: str) -> str:
    """从语料里随机抽一条，尽量避免和该类上一次抽的重复。key 是语料类别名。"""
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    last = _last_idx.get(key, -1)
    idx = random.randrange(len(items))
    for _ in range(5):  # 抽重了就重抽，几次后认命（理论上几乎不会）
        if idx != last:
            break
        idx = random.randrange(len(items))
    _last_idx[key] = idx
    return items[idx]
